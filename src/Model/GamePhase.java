package Model;

/** השלב הנוכחי בתור. */
public enum GamePhase {
    /** השחקן צריך להטיל קובייה. */
    ROLL,
    /** השחקן צריך לבחור כלי להזיז. */
    MOVE,
    /** הכלי נחת על משבצת שאלה, ושחקן צריך לענות (FR-38). */
    QUESTION,
    /** הכלי נחת על משבצת הפתעה, ואירוע ההפתעה מחכה לביצוע (FR-44). */
    SURPRISE,
    /** המשחק נגמר. */
    OVER
}
