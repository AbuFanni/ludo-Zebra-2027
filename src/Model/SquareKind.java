package Model;

/**
 * סוגי המשבצות בלוח, כפי שמוגדרים במסמך הפרויקט.
 */
public enum SquareKind {
    /** משבצת רגילה במסלול. */
    REGULAR,
    /** משבצת הגנה (כוכב). */
    SAFE,
    /** משבצת התחלה (#) של שחקן. מוגנת. */
    START,
    /** משבצת חץ בצבע שחקן: מעבירה את הכלי שלו למסלול הבא. לשאר השחקנים היא רגילה. */
    ARROW,
    /** משבצת במסלול הבית האישי של שחקן. רק הכלים שלו נכנסים אליה. */
    HOME_PATH,
    /** בית הסיום של שחקן. */
    FINISH,
    /** משבצת שאלה (?). */
    QUESTION,
    /** משבצת הפתעה. מוגנת. */
    SURPRISE
}
